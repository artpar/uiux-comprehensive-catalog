function DangerousActionReviewGoodUx() {
  const [mode, setMode] = useState<DangerousActionReviewMode>("armed");
  return (
    <div className="quality-example dangerous-action-review-demo">
      <div className="demo-row dangerous-action-review-controls" aria-label="Dangerous-action review exercise controls">
        {dangerousActionReviewGoodLabels.map(([key, label]) => (
          <button
            type="button"
            key={key}
            className={mode === key ? "demo-button small primary" : "demo-button small"}
            onClick={() => setMode(key)}
          >
            {label}
          </button>
        ))}
      </div>
      <DangerousActionReviewPanel mode={mode} idSuffix="good-ux" />
      <p className="demo-status" aria-live="polite">Dangerous-action review state: {dangerousActionReviewGoodLabels.find(([key]) => key === mode)?.[1]}.</p>
    </div>
  );
}

